/**
 * JSON envelope and DTOs exchanged between Route Handlers and client components.
 * Every API returns `{ ok: true, data }` or `{ ok: false, error }`.
 */
import type { DrawRecord, GachaStatus, PublicUser } from "@/lib/types";

export interface ApiErrorBody {
  code: string;
  message: string;
  details?: unknown;
}

export type ApiResponse<T> = { ok: true; data: T } | { ok: false; error: ApiErrorBody };

export interface Balances {
  tickets: number;
  points: number;
}

export interface MeResponse {
  user: PublicUser | null;
}

/** GET /api/gachas/[id]/remaining — fetched on page load and right after a draw. */
export interface RemainingInfo {
  gachaId: string;
  totalSlots: number;
  remainingSlots: number;
  status: GachaStatus;
  lastOneWinner: { nickname: string; at: string } | null;
  fetchedAt: string;
}

/** POST /api/gachas/[id]/draw */
export interface DrawRequestBody {
  count: number;
  /** Idempotency key generated by the client (crypto.randomUUID()). */
  requestId: string;
}

export interface DrawResponse {
  draw: DrawRecord;
  /** true when the same requestId was already processed and the stored result is returned. */
  replayed: boolean;
  balances: Balances;
  remaining: RemainingInfo;
}
